\set ON_ERROR_STOP on

BEGIN;
SET LOCAL TIME ZONE 'UTC';

CREATE SCHEMA IF NOT EXISTS silver;

CREATE TABLE IF NOT EXISTS silver.sources (
    source_id TEXT PRIMARY KEY,
    nom TEXT NOT NULL,
    url_flux TEXT NOT NULL,
    type TEXT NOT NULL,
    region TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS silver.executions_silver (
    execution_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    debut TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fin TIMESTAMPTZ,
    statut TEXT NOT NULL DEFAULT 'en_cours'
        CHECK (statut IN ('en_cours', 'termine', 'echec')),
    version_regles TEXT NOT NULL,
    CONSTRAINT executions_silver_dates_coherentes CHECK (fin IS NULL OR fin >= debut)
);

CREATE TABLE IF NOT EXISTS silver.articles_propres (
    article_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    execution_id BIGINT NOT NULL REFERENCES silver.executions_silver (execution_id),
    source_id TEXT NOT NULL REFERENCES silver.sources (source_id),
    identifiant_article TEXT NOT NULL,
    reference_bronze TEXT NOT NULL,
    position_item INTEGER NOT NULL CHECK (position_item >= 1),
    date_collecte TIMESTAMPTZ NOT NULL,
    titre TEXT NOT NULL,
    extrait TEXT NOT NULL,
    lien TEXT NOT NULL,
    date_publication TIMESTAMPTZ NOT NULL,
    date_traitement TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT articles_propres_identite_unique UNIQUE (source_id, identifiant_article),
    CONSTRAINT articles_propres_item_unique
        UNIQUE (execution_id, reference_bronze, position_item)
);

CREATE TABLE IF NOT EXISTS silver.rejets (
    rejet_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    execution_id BIGINT NOT NULL REFERENCES silver.executions_silver (execution_id),
    source_id TEXT NOT NULL REFERENCES silver.sources (source_id),
    reference_bronze TEXT NOT NULL,
    position_item INTEGER NOT NULL CHECK (position_item >= 1),
    date_collecte TIMESTAMPTZ NOT NULL,
    regles_rejet TEXT[] NOT NULL,
    date_traitement TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT rejets_regles_valides CHECK (cardinality(regles_rejet) > 0),
    CONSTRAINT rejets_item_unique UNIQUE (execution_id, reference_bronze, position_item)
);

CREATE INDEX IF NOT EXISTS executions_silver_debut_idx
    ON silver.executions_silver (debut);
CREATE INDEX IF NOT EXISTS articles_propres_publication_idx
    ON silver.articles_propres (date_publication);
CREATE INDEX IF NOT EXISTS articles_propres_execution_source_idx
    ON silver.articles_propres (execution_id, source_id);
CREATE INDEX IF NOT EXISTS rejets_execution_source_idx
    ON silver.rejets (execution_id, source_id);
CREATE INDEX IF NOT EXISTS rejets_source_idx ON silver.rejets (source_id);

COMMENT ON TABLE silver.executions_silver IS
    'Passages du traitement bronze vers silver, avec la version des règles appliquées.';
COMMENT ON COLUMN silver.articles_propres.identifiant_article IS
    'Identifiant stable par source, préfixé guid: ou url: selon le champ disponible.';
COMMENT ON COLUMN silver.articles_propres.execution_id IS
    'Exécution de la première acceptation de cet article.';
COMMENT ON COLUMN silver.articles_propres.reference_bronze IS
    'URI du JSON bronze contenant l''item, de forme s3://bucket/clé ou file:///chemin.';
COMMENT ON COLUMN silver.articles_propres.position_item IS
    'Position de l''item dans le flux bronze, numérotée à partir de 1.';
COMMENT ON COLUMN silver.rejets.regles_rejet IS
    'Identifiants des règles déclenchées, par exemple {R01_publi,R02_horoscope}.';

COMMIT;
